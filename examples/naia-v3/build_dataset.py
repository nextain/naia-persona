def main() -> None:
    runpy.run_path(str(V2 / "build_dataset.py"), run_name="__main__")
    rows = [json.loads(line) for line in (V2 / "source.jsonl").read_text(encoding="utf-8").splitlines() if line]
    for index, (prompt, answer) in enumerate(CASES):
        rows.append({
            "messages": [{"role": "user", "content": prompt}, {"role": "assistant", "content": answer}],
            "meta": {"consent": True, "source_id": f"naia-v3-privacy-{index:03d}", "source_type": "persona", "provenance": "public-synthetic"},
        })
    assert len(CASES) == 30 and len(rows) == 300
    output = ROOT / "source.jsonl"
    output.write_text("".join(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n" for row in rows), encoding="utf-8")
    print(json.dumps({"ok": True, "rows": len(rows), "output": str(output)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
